(async () => {
  const pool = await sql.connect(config);
  console.log(`Connected. Seeding ${SUPPLIERS.length} suppliers...`);

  // First delete demo suppliers that came with seed (SupplierCode starting with SUP-)
  await pool.request().query(
    "DELETE FROM dbo.Suppliers WHERE SupplierCode LIKE 'SUP-%' AND SupplierId NOT IN (SELECT DISTINCT SupplierId FROM dbo.DeliveryEntries)"
  );
  console.log('Cleaned demo suppliers not referenced by entries.');

  let inserted = 0, skipped = 0;

  for (let i = 0; i < SUPPLIERS.length; i++) {
    const name = SUPPLIERS[i];
    // Generate code: NCF-0001 thru NCF-NNNN
    const code = `NCF-${String(i + 1).padStart(4, '0')}`;

    try {
      // Skip if supplier name already exists
      const exists = await pool.request()
        .input('name', sql.NVarChar(200), name)
        .query('SELECT SupplierId FROM dbo.Suppliers WHERE SupplierName = @name');

      if (exists.recordset.length > 0) {
        skipped++;
        continue;
      }

      // Check if code conflicts
      const codeExists = await pool.request()
        .input('code', sql.VarChar(20), code)
        .query('SELECT SupplierId FROM dbo.Suppliers WHERE SupplierCode = @code');

      const finalCode = codeExists.recordset.length > 0
        ? `NCF-${String(i + 1).padStart(4, '0')}X`
        : code;

      await pool.request()
        .input('code', sql.VarChar(20), finalCode)
        .input('name', sql.NVarChar(200), name)
        .query('INSERT INTO dbo.Suppliers (SupplierCode, SupplierName, IsActive) VALUES (@code, @name, 1)');

      inserted++;
      if (inserted % 100 === 0) console.log(`  ...${inserted} inserted`);
    } catch (err) {
      console.log(`  SKIP "${name}": ${err.message}`);
      skipped++;
    }
  }

  console.log(`\nDone: ${inserted} inserted, ${skipped} skipped (already exist).`);
  console.log(`Total suppliers in DB: ${(await pool.request().query('SELECT COUNT(*) AS c FROM dbo.Suppliers')).recordset[0].c}`);
  await pool.close();
  process.exit(0);
})().catch(e => { console.error('FATAL:', e.message); process.exit(1); });
